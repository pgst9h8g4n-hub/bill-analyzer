// 把任意来源的分类名/关键词归一化成标准分类名，匹配不到返回 ''
export function normalizeCategoryName(input: string): string {
  const s = (input || '').trim();
  if (!s) return '';
  if (CATEGORY_ALIASES[s]) return CATEGORY_ALIASES[s];
  // 把 input 当关键词搜 MERCHANT_CATEGORY（长词优先）
  const sorted = [...MERCHANT_CATEGORY].sort((a, b) => b[0].length - a[0].length);
  for (const [keyword, catName] of sorted) {
    if (s.includes(keyword) || keyword.includes(s)) return catName;
  }
  // 精确匹配大类名
  const bigNames = MERCHANT_CATEGORY.map(x => x[1]);
  if (bigNames.includes(s)) return s;
  return '';
}

// 用商户名 + 文本关键词匹配出标准分类名（长词优先），匹配不到返回 ''
export function matchKeywordCategory(text: string, merchant?: string): string {
  const haystacks = [text, merchant ?? ''];
  const sorted = [...MERCHANT_CATEGORY].sort((a, b) => b[0].length - a[0].length);
  for (const [keyword, catName] of sorted) {
    if (haystacks.some(h => h.includes(keyword))) return catName;
  }
  return '';
}
